## GeneralDisp

`GeneralDisp` comes from the same paper: Section 4 and Algorithms 2–5, the
general HEO-DFS with the Zombie method. Agents may start on any nodes. Every
group of co-located agents, labelled `(level, leader)`, runs its own HEO-DFS.
When two groups meet, the weaker leader becomes a **zombie** that chases the
stronger group until that group's leader settles it.

Time runs in units of twelve slots. Each slot is one step, committed through
`apply_move_intents` even when nobody moves. [general-disp.md](general-disp.md)
has:
- the slot table;
- the decisions taken where the pseudocode leaves a choice;
- the two-group and three-group hand traces.

Probing works differently from RootedDisp:
- One pass fits in one unit, and `ψ(w)` keeps `next`, `checked` and `done`
  between units.
- A prober counts a node as visited only if its settler belongs to the probing
  leader's group.
- Recruited settlers walk over through `help` in slot 3.
- In slot 4, a helper of a weaker group is sent home for good, and a recruited
  helper that never came marks its port as leading out.

```mermaid
flowchart TD
    A["simulate() / run()"] --> B{"legitimate()? checked before every step"}
    B -- yes --> Z["Termination::Completed"]
    B -- no --> S1["slot1_election(): weaker leaders become zombies"]

    subgraph unit ["one unit, twelve steps"]
        S1 --> S2["slot2_settle(): settle or incorporate, level up, start a probe"]
        S2 --> S3["slot3_helpers_go(): settlers follow help"]
        S3 --> S4["slot4_check(): missing helpers, dismiss weaker ones"]
        S4 --> S5["slot5_finish(): a finished probe sends helpers home"]
        S5 --> S6["slot6_probe_out()"]
        S6 --> S7["slot7_probe_back(): same-group settler? recruit it"]
        S7 --> S8["slot8_tally(): next = smallest port with no find"]
        S8 --> C["chase(): weak zombies in slot 9, all in slot 10"]
        C --> S11["slot11_move(): forward through next, or back to parent"]
        S11 --> S12["slot12_parent(): parent = pin"]
    end

    S12 --> B
    S6 -. "every slot validated, then committed" .-> F1["commit()"]
```

HEADER

