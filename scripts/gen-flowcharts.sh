## RootedDisp

`RootedDisp` from Sudo, Shibata, Nakamura, Kim and Masuzawa, *Near-linear Time
Dispersion of Mobile Agents*, Section 3 and Algorithm 1: the rooted HEO-DFS. The
agent with the largest ID leads a depth-first search, and the smallest-ID
explorer settles at each node it reaches. Every box below that moves agents is
exactly one synchronous step, committed through `apply_move_intents`; settling
takes none. [rooted-disp.md](rooted-disp.md) has the time model, the decisions
taken where Algorithm 1 leaves a choice, and two worked traces.

What makes the search fast is `probe_pass`. Every agent at the node except its
settler takes one port; a settler found at home comes back as a **helper** and
probes in the next pass too, so the probers double until one finds an
unsettled neighbour. `probe` resets `next` and `checked` on every call, so no
cursor survives from an earlier visit.

```mermaid
flowchart TD
    A["simulate() / run()"] --> B["smallest ID settles at the root (line 1)"]
    B --> C["disperse()"]
    C --> D{"a_max settled? (line 2)"}
    D -- yes --> Z["Termination::Completed"]
    D -- no --> E["probe(): reset next, checked (line 14)"]

    subgraph probing ["Probe(), lines 12-22"]
        E --> F["probe_pass(): probe out, then probe back"]
        F --> G{"unsettled neighbour found, or every port checked?"}
        G -- "no: helpers join, probers double" --> F
        G -- yes --> H["helpers_home() (line 22), only if a helper is away"]
    end

    H --> I{"next set?"}
    I -- yes --> J["forward(): explorers move, smallest ID settles, parent = a_max.pin"]
    I -- no --> K["backward(): explorers move to the parent (line 11)"]
    J --> D
    K --> E

    F -. "every move of a step validated, then committed" .-> F1["commit()"]
```

HEADER

