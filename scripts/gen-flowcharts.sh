## Reading the five together

All five settle one agent per node and all five are depth-first, but they
differ in who does the looking and what the tree is for.

| | Drop and Freeze | Help by Scouts | P1Tree | RootedDisp | GeneralDisp |
| --- | --- | --- | --- | --- | --- |
| Start | any placement, without groups or merging | rooted only | rooted only | rooted only | any placement |
| Who probes | unsettled agents, one per port | unsettled agents plus vacated settlers | unsettled agents plus vacated settlers | explorers plus settlers recruited as helpers during the probe | each group's leader, zombies and helpers of the same group |
| Probe cost | one port per agent per round | parallel across scouts | parallel, and stops at the first find | probers double each pass; `O(log τ)` passes | as RootedDisp, one pass per twelve-step unit |
| Port labels | overwritten by `canonicalize_ports` | as given | as given, and central to the result | as given | as given |
| Tree | incidental to the walk | carries the retrace | the object being built | parent ports for backtracking | one per group; a stronger group takes over a weaker one's settlers |
| Stops when | every agent is settled | every agent is settled | every agent is settled | the leader settles, last | the configuration is legitimate; a leader may end waiting alone |

The port-label row is the one that catches people out. Drop-and-Freeze discards
the port assignment an experiment asked for, so sweeping `--ports` changes
nothing for it; P1Tree's whole behaviour turns on which edges happen to carry
port 1.
